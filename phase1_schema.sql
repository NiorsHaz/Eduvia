-- =====================================================================
-- High School Management System: Phase 1 schema (PostgreSQL 15+)
-- Scope: auth, students, guardians, staff, academic structure,
--        timetable, attendance, document records, import tracking.
--
-- Conventions
--   * bigint identity PKs (Laravel/Eloquent friendly)
--   * text + CHECK instead of PG enums (easier to evolve via migrations)
--   * timestamptz everywhere; school timezone handled in the app
--   * soft deletes (deleted_at) on records that must keep history
--   * ON DELETE RESTRICT by default: history is never silently lost
--   * Roles/permissions tables come from spatie/laravel-permission
--     (roles, permissions, model_has_roles, model_has_permissions,
--      role_has_permissions) and audit from spatie/laravel-activitylog
--     (activity_log). Do not hand-write those; publish package migrations.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- needed for exclusion constraints
CREATE EXTENSION IF NOT EXISTS citext;       -- case-insensitive emails

-- Time-of-day range, used to detect timetable overlaps
CREATE TYPE timerange AS RANGE (subtype = time);

-- ---------------------------------------------------------------------
-- 1. CAMPUS (single row today; keeps multi-campus possible later)
-- ---------------------------------------------------------------------
CREATE TABLE campuses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    code        text NOT NULL UNIQUE,
    address     text,
    phone       text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 2. USERS (login accounts; roles via spatie tables)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id           bigint REFERENCES campuses(id),
    name                text NOT NULL,
    email               citext UNIQUE,
    phone               text UNIQUE,            -- many families log in by phone
    password            text NOT NULL,          -- bcrypt/argon2 hash
    locale              text NOT NULL DEFAULT 'fr' CHECK (locale IN ('fr','mg','en')),
    status              text NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active','suspended','deactivated')),
    email_verified_at   timestamptz,
    last_login_at       timestamptz,
    must_change_password boolean NOT NULL DEFAULT false,
    remember_token      text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz,
    CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

CREATE TABLE login_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint REFERENCES users(id) ON DELETE CASCADE,
    identifier  text NOT NULL,                  -- what was typed (failed logins too)
    success     boolean NOT NULL,
    ip_address  inet,
    user_agent  text,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_login_history_user ON login_history (user_id, created_at DESC);

-- Temporary access / substitute assignments (permission expiry)
CREATE TABLE temporary_role_grants (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_name   text NOT NULL,                  -- matches spatie roles.name
    granted_by  bigint NOT NULL REFERENCES users(id),
    starts_at   timestamptz NOT NULL,
    expires_at  timestamptz NOT NULL,
    reason      text,
    revoked_at  timestamptz,
    CHECK (expires_at > starts_at)
);

-- ---------------------------------------------------------------------
-- 3. DEPARTMENTS, STAFF
-- ---------------------------------------------------------------------
CREATE TABLE departments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id   bigint REFERENCES campuses(id),
    name        text NOT NULL,
    head_staff_id bigint,                       -- FK added after staff exists
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campus_id, name)
);

CREATE TABLE staff (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint UNIQUE REFERENCES users(id),
    campus_id         bigint REFERENCES campuses(id),
    department_id     bigint REFERENCES departments(id),
    employee_number   text NOT NULL UNIQUE,
    first_name        text NOT NULL,
    last_name         text NOT NULL,
    gender            text CHECK (gender IN ('female','male','other')),
    date_of_birth     date,
    national_id       text,                     -- restricted field
    phone             text,
    email             citext,
    address           text,
    position          text NOT NULL,            -- e.g. teacher, accountant
    staff_type        text NOT NULL DEFAULT 'teacher'
                      CHECK (staff_type IN ('teacher','administrative','finance','library','support','other')),
    qualifications    text,
    employment_status text NOT NULL DEFAULT 'active'
                      CHECK (employment_status IN ('active','on_leave','suspended','resigned','terminated','retired')),
    hire_date         date,
    contract_end_date date,
    photo_path        text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    deleted_at        timestamptz
);
CREATE INDEX idx_staff_name ON staff (last_name, first_name);

ALTER TABLE departments
    ADD CONSTRAINT fk_departments_head FOREIGN KEY (head_staff_id) REFERENCES staff(id);

-- ---------------------------------------------------------------------
-- 4. ACADEMIC STRUCTURE
-- ---------------------------------------------------------------------
CREATE TABLE academic_years (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id   bigint REFERENCES campuses(id),
    name        text NOT NULL,                  -- '2026-2027'
    start_date  date NOT NULL,
    end_date    date NOT NULL,
    status      text NOT NULL DEFAULT 'planned'
                CHECK (status IN ('planned','active','closed','archived')),
    is_current  boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date > start_date),
    UNIQUE (campus_id, name)
);
-- Only one current academic year at a time
CREATE UNIQUE INDEX uq_one_current_year ON academic_years ((true)) WHERE is_current;

-- Terms / trimesters / semesters
CREATE TABLE terms (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),
    name              text NOT NULL,
    sequence          smallint NOT NULL,
    start_date        date NOT NULL,
    end_date          date NOT NULL,
    data_entry_open   boolean NOT NULL DEFAULT true,   -- admin can lock grade/attendance entry
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date > start_date),
    UNIQUE (academic_year_id, sequence),
    EXCLUDE USING gist (academic_year_id WITH =, daterange(start_date, end_date, '[]') WITH &&)
);

-- Holidays, closures, exam windows, deadlines (feeds the calendar later)
CREATE TABLE calendar_periods (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),
    type              text NOT NULL CHECK (type IN ('holiday','closure','exam_window','deadline','other')),
    title             text NOT NULL,
    start_date        date NOT NULL,
    end_date          date NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);

CREATE TABLE buildings (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id   bigint REFERENCES campuses(id),
    name        text NOT NULL,
    UNIQUE (campus_id, name)
);

CREATE TABLE rooms (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id bigint REFERENCES buildings(id),
    name        text NOT NULL,
    room_type   text NOT NULL DEFAULT 'classroom'
                CHECK (room_type IN ('classroom','laboratory','library','hall','sports','office','other')),
    capacity    integer CHECK (capacity > 0),
    is_active   boolean NOT NULL DEFAULT true,
    UNIQUE (building_id, name)
);

-- Levels: e.g. 6e, 5e, 4e, 3e, 2nde, 1ere, Terminale
CREATE TABLE levels (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    name        text NOT NULL,
    cycle       text,                           -- college / lycee
    sort_order  smallint NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Educational tracks / series (e.g. Terminale A, C, D)
CREATE TABLE tracks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    name        text NOT NULL
);

-- A class in a given academic year (e.g. '3e B, 2026-2027')
CREATE TABLE classes (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id     bigint NOT NULL REFERENCES academic_years(id),
    level_id             bigint NOT NULL REFERENCES levels(id),
    track_id             bigint REFERENCES tracks(id),
    name                 text NOT NULL,         -- 'B', 'Section 2'
    capacity             integer NOT NULL DEFAULT 40 CHECK (capacity > 0),
    supervisor_staff_id  bigint REFERENCES staff(id),
    home_room_id         bigint REFERENCES rooms(id),
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    deleted_at           timestamptz,
    UNIQUE (academic_year_id, level_id, name)
);
CREATE INDEX idx_classes_supervisor ON classes (supervisor_staff_id);

CREATE TABLE subjects (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    name        text NOT NULL,                  -- translations can live in lang files
    is_optional boolean NOT NULL DEFAULT false,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Subject definition per level/track and academic year (coefficient, hours)
CREATE TABLE level_subjects (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),
    level_id          bigint NOT NULL REFERENCES levels(id),
    track_id          bigint REFERENCES tracks(id),
    subject_id        bigint NOT NULL REFERENCES subjects(id),
    coefficient       numeric(4,2) NOT NULL DEFAULT 1 CHECK (coefficient >= 0),
    weekly_hours      numeric(4,1),
    UNIQUE NULLS NOT DISTINCT (academic_year_id, level_id, track_id, subject_id)
);

-- Which teacher teaches which subject in which class.
-- Authorization rule: a teacher can act only on rows listed here.
CREATE TABLE class_subject_teachers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id    bigint NOT NULL REFERENCES classes(id),
    subject_id  bigint NOT NULL REFERENCES subjects(id),
    staff_id    bigint NOT NULL REFERENCES staff(id),
    starts_on   date,
    ends_on     date,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (ends_on IS NULL OR starts_on IS NULL OR ends_on >= starts_on),
    UNIQUE (class_id, subject_id, staff_id)
);
CREATE INDEX idx_cst_staff ON class_subject_teachers (staff_id);

-- ---------------------------------------------------------------------
-- 5. GUARDIANS
-- ---------------------------------------------------------------------
CREATE TABLE guardians (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint UNIQUE REFERENCES users(id),   -- null until account activated
    first_name  text NOT NULL,
    last_name   text NOT NULL,
    phone       text,
    phone_alt   text,
    email       citext,
    address     text,
    occupation  text,
    national_id text,                                  -- used for identity verification
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    deleted_at  timestamptz
);
CREATE INDEX idx_guardians_phone ON guardians (phone);
CREATE INDEX idx_guardians_name  ON guardians (last_name, first_name);

-- ---------------------------------------------------------------------
-- 6. STUDENTS
-- ---------------------------------------------------------------------
CREATE TABLE students (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint UNIQUE REFERENCES users(id),
    campus_id         bigint REFERENCES campuses(id),
    student_number    text NOT NULL UNIQUE,        -- generated unique identifier
    first_name        text NOT NULL,
    last_name         text NOT NULL,
    gender            text CHECK (gender IN ('female','male','other')),
    date_of_birth     date NOT NULL,
    place_of_birth    text,
    nationality       text,
    address           text,
    phone             text,
    email             citext,
    photo_path        text,
    previous_school   text,
    status            text NOT NULL DEFAULT 'enrolled'
                      CHECK (status IN ('applicant','enrolled','suspended','withdrawn',
                                        'transferred_out','graduated','alumni')),
    admission_date    date,
    exit_date         date,
    exit_reason       text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    deleted_at        timestamptz
);
CREATE INDEX idx_students_name   ON students (last_name, first_name);
CREATE INDEX idx_students_status ON students (status);
-- Duplicate-detection helper (not unique: twins and common names exist)
CREATE INDEX idx_students_dup ON students (lower(last_name), lower(first_name), date_of_birth);

-- Restricted medical / emergency data: separate table, separate permission
CREATE TABLE student_health_records (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          bigint NOT NULL UNIQUE REFERENCES students(id),
    allergies           text,
    medical_conditions  text,
    medications         text,
    emergency_notes     text,
    updated_by          bigint REFERENCES users(id),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

-- Guardian <> student link, with verification and revocable access
CREATE TABLE student_guardians (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          bigint NOT NULL REFERENCES students(id),
    guardian_id         bigint NOT NULL REFERENCES guardians(id),
    relationship        text NOT NULL
                        CHECK (relationship IN ('mother','father','legal_guardian','grandparent','sibling','other')),
    is_primary_contact  boolean NOT NULL DEFAULT false,
    is_emergency_contact boolean NOT NULL DEFAULT false,
    is_authorized_pickup boolean NOT NULL DEFAULT false,
    can_view_academic   boolean NOT NULL DEFAULT true,
    can_view_finance    boolean NOT NULL DEFAULT true,
    verified_at         timestamptz,               -- portal access requires non-null
    verified_by         bigint REFERENCES users(id),
    revoked_at          timestamptz,
    revoked_by          bigint REFERENCES users(id),
    revoke_reason       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (student_id, guardian_id)
);
CREATE INDEX idx_sg_guardian ON student_guardians (guardian_id);
-- At most one primary contact per student
CREATE UNIQUE INDEX uq_primary_contact ON student_guardians (student_id)
    WHERE is_primary_contact AND revoked_at IS NULL;

-- Admissions pipeline
CREATE TABLE applications (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id    bigint NOT NULL REFERENCES academic_years(id),
    level_id            bigint NOT NULL REFERENCES levels(id),
    student_id          bigint REFERENCES students(id),   -- set once accepted/enrolled
    applicant_first_name text NOT NULL,
    applicant_last_name  text NOT NULL,
    date_of_birth       date NOT NULL,
    guardian_name       text,
    guardian_phone      text,
    guardian_email      citext,
    previous_school     text,
    status              text NOT NULL DEFAULT 'submitted'
                        CHECK (status IN ('submitted','under_review','accepted','waitlisted','rejected','enrolled')),
    documents_complete  boolean NOT NULL DEFAULT false,
    decision_by         bigint REFERENCES users(id),
    decision_at         timestamptz,
    decision_note       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_applications_status ON applications (academic_year_id, status);

-- Enrollment history: which class a student was in, and when.
-- Class transfers close one row and open another (history preserved).
CREATE TABLE enrollments (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        bigint NOT NULL REFERENCES students(id),
    class_id          bigint NOT NULL REFERENCES classes(id),
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),  -- denormalized from class
    start_date        date NOT NULL,
    end_date          date,                                           -- null = still in class
    status            text NOT NULL DEFAULT 'active'
                      CHECK (status IN ('active','transferred','withdrawn','completed')),
    outcome           text CHECK (outcome IN ('promoted','repeat','graduated','left')),
    created_by        bigint REFERENCES users(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date IS NULL OR end_date >= start_date),
    -- A student cannot be in two classes at the same time within a year.
    -- '[)' lets a transfer end one row and start the next on the same day.
    EXCLUDE USING gist (
        student_id WITH =,
        academic_year_id WITH =,
        daterange(start_date, end_date, '[)') WITH &&
    )
);
CREATE INDEX idx_enrollments_class   ON enrollments (class_id) WHERE end_date IS NULL;
CREATE INDEX idx_enrollments_student ON enrollments (student_id);

-- ---------------------------------------------------------------------
-- 7. DOCUMENTS (records only; files live in private S3-compatible storage)
-- ---------------------------------------------------------------------
CREATE TABLE documents (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type      text NOT NULL CHECK (owner_type IN ('student','staff','guardian','application')),
    owner_id        bigint NOT NULL,
    category        text NOT NULL,              -- birth_certificate, transcript, ...
    title           text NOT NULL,
    storage_path    text NOT NULL,              -- never a public URL
    mime_type       text,
    size_bytes      bigint,
    version         integer NOT NULL DEFAULT 1,
    status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
    uploaded_by     bigint REFERENCES users(id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    archived_at     timestamptz
);
CREATE INDEX idx_documents_owner ON documents (owner_type, owner_id);

-- ---------------------------------------------------------------------
-- 8. TIMETABLE
-- ---------------------------------------------------------------------
CREATE TABLE timetable_entries (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),
    class_id          bigint NOT NULL REFERENCES classes(id),
    subject_id        bigint NOT NULL REFERENCES subjects(id),
    staff_id          bigint NOT NULL REFERENCES staff(id),
    room_id           bigint REFERENCES rooms(id),
    day_of_week       smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- ISO, 1 = Monday
    start_time        time NOT NULL,
    end_time          time NOT NULL,
    valid_from        date NOT NULL,
    valid_to          date,                                                  -- null = until year end
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (end_time > start_time),
    CHECK (valid_to IS NULL OR valid_to >= valid_from),

    -- Conflict detection enforced by the database itself
    CONSTRAINT no_teacher_overlap EXCLUDE USING gist (
        staff_id WITH =, day_of_week WITH =,
        timerange(start_time, end_time) WITH &&,
        daterange(valid_from, valid_to, '[]') WITH &&),
    CONSTRAINT no_class_overlap EXCLUDE USING gist (
        class_id WITH =, day_of_week WITH =,
        timerange(start_time, end_time) WITH &&,
        daterange(valid_from, valid_to, '[]') WITH &&),
    CONSTRAINT no_room_overlap EXCLUDE USING gist (
        room_id WITH =, day_of_week WITH =,
        timerange(start_time, end_time) WITH &&,
        daterange(valid_from, valid_to, '[]') WITH &&)
);
CREATE INDEX idx_tt_class ON timetable_entries (class_id, day_of_week);
CREATE INDEX idx_tt_staff ON timetable_entries (staff_id, day_of_week);

-- One-off changes: cancellations, substitutes, moves
CREATE TABLE timetable_exceptions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timetable_entry_id   bigint NOT NULL REFERENCES timetable_entries(id) ON DELETE CASCADE,
    exception_date       date NOT NULL,
    type                 text NOT NULL CHECK (type IN ('cancelled','substitute','room_change')),
    substitute_staff_id  bigint REFERENCES staff(id),
    substitute_room_id   bigint REFERENCES rooms(id),
    reason               text,
    created_by           bigint REFERENCES users(id),
    created_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (timetable_entry_id, exception_date),
    CHECK (type <> 'substitute' OR substitute_staff_id IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- 9. ATTENDANCE
-- ---------------------------------------------------------------------
-- One session = one class on one date (optionally tied to a lesson)
CREATE TABLE attendance_sessions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id             bigint NOT NULL REFERENCES classes(id),
    term_id              bigint REFERENCES terms(id),
    session_date         date NOT NULL,
    timetable_entry_id   bigint REFERENCES timetable_entries(id),  -- null = daily roll call
    taken_by             bigint NOT NULL REFERENCES users(id),
    submitted_at         timestamptz,
    client_uuid          uuid UNIQUE,            -- idempotency key for offline mobile sync
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()
);
-- One daily roll call per class/date; one per lesson otherwise
CREATE UNIQUE INDEX uq_att_daily  ON attendance_sessions (class_id, session_date)
    WHERE timetable_entry_id IS NULL;
CREATE UNIQUE INDEX uq_att_lesson ON attendance_sessions (class_id, session_date, timetable_entry_id)
    WHERE timetable_entry_id IS NOT NULL;

CREATE TABLE attendance_records (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    bigint NOT NULL REFERENCES attendance_sessions(id) ON DELETE CASCADE,
    student_id    bigint NOT NULL REFERENCES students(id),
    status        text NOT NULL CHECK (status IN ('present','absent','late','excused','left_early')),
    minutes_late  smallint CHECK (minutes_late >= 0),
    note          text,
    marked_by     bigint NOT NULL REFERENCES users(id),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (session_id, student_id)
);
CREATE INDEX idx_att_student ON attendance_records (student_id, status);

-- Every change to a record is kept (who, when, from what to what).
-- Populate from a Laravel observer or a trigger; activity_log also covers this.
CREATE TABLE attendance_record_history (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id     bigint NOT NULL REFERENCES attendance_records(id) ON DELETE CASCADE,
    old_status    text,
    new_status    text NOT NULL,
    changed_by    bigint NOT NULL REFERENCES users(id),
    reason        text,
    changed_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE absence_justifications (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_record_id  bigint REFERENCES attendance_records(id),
    student_id            bigint NOT NULL REFERENCES students(id),
    submitted_by          bigint NOT NULL REFERENCES users(id),   -- guardian account
    date_from             date NOT NULL,
    date_to               date NOT NULL,
    reason                text NOT NULL,
    attachment_document_id bigint REFERENCES documents(id),
    status                text NOT NULL DEFAULT 'pending'
                          CHECK (status IN ('pending','approved','rejected','more_info_requested')),
    reviewed_by           bigint REFERENCES users(id),
    reviewed_at           timestamptz,
    review_note           text,
    created_at            timestamptz NOT NULL DEFAULT now(),
    CHECK (date_to >= date_from)
);
CREATE INDEX idx_just_status ON absence_justifications (status, created_at DESC);

-- ---------------------------------------------------------------------
-- 10. BULK IMPORT TRACKING (repeatable, auditable imports)
-- ---------------------------------------------------------------------
CREATE TABLE import_batches (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity        text NOT NULL CHECK (entity IN ('students','guardians','staff','classes')),
    file_name     text NOT NULL,
    status        text NOT NULL DEFAULT 'uploaded'
                  CHECK (status IN ('uploaded','validated','failed_validation','committed','rolled_back')),
    total_rows    integer,
    valid_rows    integer,
    error_rows    integer,
    imported_by   bigint NOT NULL REFERENCES users(id),
    committed_at  timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE import_batch_errors (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    bigint NOT NULL REFERENCES import_batches(id) ON DELETE CASCADE,
    row_number  integer NOT NULL,
    field       text,
    message     text NOT NULL
);

