-- 8. REPORTING VIEWS
-- ---------------------------------------------------------------------
-- Assessments where an actively enrolled student has no grade row yet
CREATE OR REPLACE VIEW v_missing_grades AS
SELECT a.id            AS assessment_id,
       a.title,
       cst.class_id,
       cst.subject_id,
       a.term_id,
       e.student_id
FROM assessments a
JOIN class_subject_teachers cst ON cst.id = a.class_subject_teacher_id
JOIN enrollments e ON e.class_id = cst.class_id
                  AND e.end_date IS NULL
                  AND e.status = 'active'
LEFT JOIN grades g ON g.assessment_id = a.id AND g.student_id = e.student_id
WHERE a.deleted_at IS NULL
  AND a.status IN ('open','submitted')
  AND (g.id IS NULL OR g.status = 'not_graded');

-- Per-assessment statistics for grade distribution charts
CREATE OR REPLACE VIEW v_assessment_stats AS
SELECT a.id AS assessment_id,
       cst.class_id,
       cst.subject_id,
       a.term_id,
       count(g.id) FILTER (WHERE g.status = 'graded')                   AS graded_count,
       round(avg(g.score / a.max_score * 20) FILTER (WHERE g.status = 'graded'), 2) AS avg_on_20,
       round(min(g.score / a.max_score * 20) FILTER (WHERE g.status = 'graded'), 2) AS min_on_20,
       round(max(g.score / a.max_score * 20) FILTER (WHERE g.status = 'graded'), 2) AS max_on_20
FROM assessments a
JOIN class_subject_teachers cst ON cst.id = a.class_subject_teacher_id
LEFT JOIN grades g ON g.assessment_id = a.id
WHERE a.deleted_at IS NULL
GROUP BY a.id, cst.class_id, cst.subject_id, a.term_id;

-- Students flagged for academic support in the latest computed term
CREATE OR REPLACE VIEW v_students_needing_support AS
SELECT tr.student_id, tr.class_id, tr.term_id, tr.average, tr.days_absent
FROM term_results tr
WHERE tr.needs_support;
