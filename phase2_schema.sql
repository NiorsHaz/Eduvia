-- =====================================================================
-- High School Management System: Phase 2 schema (PostgreSQL 15+)
-- Scope: grading policy, gradebook, validation workflow, examinations,
--        computed results, report cards, homework and assignments.
-- Depends on: phase1_schema.sql (users, staff, students, classes,
--             subjects, terms, academic_years, enrollments, rooms,
--             class_subject_teachers, documents, attendance_*).
--
-- Principles
--   * Raw scores live in `grades`; averages are computed by the Laravel
--     service and SNAPSHOTTED into result tables when a period is
--     validated, so published report cards never change silently.
--   * After validation, grades are locked by a trigger. Only the reopen
--     workflow (logged in grade_validation_events) can unlock them.
--   * Every score change is written to grade_history by a trigger.
--   * Ranking is off unless the grading policy enables it.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. GRADING POLICY
-- ---------------------------------------------------------------------
CREATE TABLE grading_scales (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL UNIQUE,              -- e.g. 'Sur 20'
    max_score   numeric(6,2) NOT NULL DEFAULT 20 CHECK (max_score > 0),
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Optional bands (appreciations / letters)
CREATE TABLE grading_scale_bands (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scale_id    bigint NOT NULL REFERENCES grading_scales(id) ON DELETE CASCADE,
    min_score   numeric(6,2) NOT NULL,
    max_score   numeric(6,2) NOT NULL,
    label       text NOT NULL,                     -- 'Tres bien', 'A', ...
    is_passing  boolean NOT NULL DEFAULT true,
    CHECK (max_score >= min_score),
    EXCLUDE USING gist (scale_id WITH =, numrange(min_score, max_score, '[]') WITH &&)
);

-- One policy per academic year, optionally overridden per level
CREATE TABLE grading_policies (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),
    level_id          bigint REFERENCES levels(id),     -- null = default for all levels
    scale_id          bigint NOT NULL REFERENCES grading_scales(id),
    pass_mark         numeric(6,2) NOT NULL DEFAULT 10,
    rounding_decimals smallint NOT NULL DEFAULT 2 CHECK (rounding_decimals BETWEEN 0 AND 4),
    rounding_mode     text NOT NULL DEFAULT 'half_up' CHECK (rounding_mode IN ('half_up','down','up')),
    ranking_enabled   boolean NOT NULL DEFAULT false,
    -- how term averages combine into the annual average, e.g. {"1":1,"2":1,"3":1}
    term_weights      jsonb NOT NULL DEFAULT '{}'::jsonb,
    -- promotion rule parameters, interpreted by the app, e.g. {"min_annual_average":10}
    promotion_rules   jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (academic_year_id, level_id)
);

CREATE TABLE assessment_types (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            text NOT NULL UNIQUE,          -- homework, quiz, practical, continuous, midterm, final
    name            text NOT NULL,
    default_weight  numeric(5,2) NOT NULL DEFAULT 1 CHECK (default_weight >= 0)
);

-- ---------------------------------------------------------------------
-- 2. ASSESSMENTS AND GRADES
-- ---------------------------------------------------------------------
-- Authorization rule: a teacher can create/grade an assessment only if
-- class_subject_teacher_id belongs to them.
CREATE TABLE assessments (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_teacher_id bigint NOT NULL REFERENCES class_subject_teachers(id),
    term_id                  bigint NOT NULL REFERENCES terms(id),
    assessment_type_id       bigint NOT NULL REFERENCES assessment_types(id),
    title                    text NOT NULL,
    assessment_date          date,
    max_score                numeric(6,2) NOT NULL DEFAULT 20 CHECK (max_score > 0),
    weight                   numeric(5,2) NOT NULL DEFAULT 1 CHECK (weight >= 0),
    status                   text NOT NULL DEFAULT 'open'
                             CHECK (status IN ('draft','open','submitted','validated')),
    created_by               bigint NOT NULL REFERENCES users(id),
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    deleted_at               timestamptz
);
CREATE INDEX idx_assessments_cst  ON assessments (class_subject_teacher_id, term_id);
CREATE INDEX idx_assessments_term ON assessments (term_id, status);

CREATE TABLE grades (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id  bigint NOT NULL REFERENCES assessments(id),
    student_id     bigint NOT NULL REFERENCES students(id),
    score          numeric(6,2) CHECK (score >= 0),    -- null while not graded
    status         text NOT NULL DEFAULT 'graded'
                   CHECK (status IN ('graded','absent','excused','not_graded')),
    comment        text,
    entered_by     bigint NOT NULL REFERENCES users(id),
    client_uuid    uuid UNIQUE,                        -- idempotent offline sync from mobile
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (assessment_id, student_id),
    -- a score is required when status = graded, forbidden otherwise
    CHECK ((status = 'graded' AND score IS NOT NULL) OR (status <> 'graded' AND score IS NULL))
);
CREATE INDEX idx_grades_student ON grades (student_id);

CREATE TABLE grade_history (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_id     bigint NOT NULL REFERENCES grades(id) ON DELETE CASCADE,
    old_score    numeric(6,2),
    new_score    numeric(6,2),
    old_status   text,
    new_status   text,
    changed_by   bigint NOT NULL REFERENCES users(id),
    reason       text,               -- app requires a reason once the period was validated/reopened
    changed_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_grade_history_grade ON grade_history (grade_id, changed_at DESC);

-- --- Trigger 1: score <= max_score, and lock validated assessments ----
CREATE OR REPLACE FUNCTION fn_grades_guard() RETURNS trigger AS $$
DECLARE
    a_status text;
    a_max    numeric;
    a_id     bigint;
BEGIN
    a_id := COALESCE(NEW.assessment_id, OLD.assessment_id);
    SELECT status, max_score INTO a_status, a_max FROM assessments WHERE id = a_id;

    IF a_status = 'validated' THEN
        RAISE EXCEPTION 'Assessment % is validated: grades are locked. Reopen it through the validation workflow.', a_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF NEW.score IS NOT NULL AND NEW.score > a_max THEN
        RAISE EXCEPTION 'Score % exceeds assessment maximum %', NEW.score, a_max
            USING ERRCODE = 'check_violation';
    END IF;

    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_grades_guard
    BEFORE INSERT OR UPDATE OR DELETE ON grades
    FOR EACH ROW EXECUTE FUNCTION fn_grades_guard();

-- --- Trigger 2: automatic history on every score/status change --------
-- The app sets the acting user and reason per transaction:
--   SELECT set_config('app.user_id', '42', true);
--   SELECT set_config('app.change_reason', 'Correction after recount', true);
CREATE OR REPLACE FUNCTION fn_grades_history() RETURNS trigger AS $$
BEGIN
    IF NEW.score IS DISTINCT FROM OLD.score OR NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO grade_history (grade_id, old_score, new_score, old_status, new_status, changed_by, reason)
        VALUES (
            OLD.id, OLD.score, NEW.score, OLD.status, NEW.status,
            COALESCE(NULLIF(current_setting('app.user_id', true), '')::bigint, NEW.entered_by),
            NULLIF(current_setting('app.change_reason', true), '')
        );
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_grades_history
    AFTER UPDATE ON grades
    FOR EACH ROW EXECUTE FUNCTION fn_grades_history();

-- ---------------------------------------------------------------------
-- 3. VALIDATION WORKFLOW (per class + subject + term)
-- ---------------------------------------------------------------------
-- The app moves all matching assessments between open -> submitted ->
-- validated (or back to open on reopen) and logs each step here.
CREATE TABLE grade_validation_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id    bigint NOT NULL REFERENCES classes(id),
    subject_id  bigint NOT NULL REFERENCES subjects(id),
    term_id     bigint NOT NULL REFERENCES terms(id),
    action      text NOT NULL CHECK (action IN ('submit','validate','reject','reopen')),
    performed_by bigint NOT NULL REFERENCES users(id),
    reason      text,                                 -- mandatory for reject/reopen (app-enforced)
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (action NOT IN ('reject','reopen') OR reason IS NOT NULL)
);
CREATE INDEX idx_gve_scope ON grade_validation_events (class_id, subject_id, term_id, created_at DESC);

-- ---------------------------------------------------------------------
-- 4. EXAMINATIONS
-- ---------------------------------------------------------------------
CREATE TABLE exam_sessions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  bigint NOT NULL REFERENCES academic_years(id),
    term_id           bigint REFERENCES terms(id),
    name              text NOT NULL,                  -- 'Examens du 1er trimestre'
    exam_type         text NOT NULL DEFAULT 'term'
                      CHECK (exam_type IN ('midterm','term','final','national_mock','other')),
    start_date        date NOT NULL,
    end_date          date NOT NULL,
    status            text NOT NULL DEFAULT 'planned'
                      CHECK (status IN ('planned','scheduled','in_progress','marking','results_validated','published','archived')),
    created_by        bigint REFERENCES users(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);

-- One paper = one subject for one class in a session
CREATE TABLE exam_schedules (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_session_id  bigint NOT NULL REFERENCES exam_sessions(id) ON DELETE CASCADE,
    class_id         bigint NOT NULL REFERENCES classes(id),
    subject_id       bigint NOT NULL REFERENCES subjects(id),
    room_id          bigint REFERENCES rooms(id),
    exam_date        date NOT NULL,
    start_time       time NOT NULL,
    end_time         time NOT NULL,
    max_score        numeric(6,2) NOT NULL DEFAULT 20 CHECK (max_score > 0),
    -- results flow into the normal gradebook through this assessment
    assessment_id    bigint UNIQUE REFERENCES assessments(id),
    CHECK (end_time > start_time),
    UNIQUE (exam_session_id, class_id, subject_id),
    -- a class cannot sit two papers at once
    EXCLUDE USING gist (class_id WITH =, exam_date WITH =, timerange(start_time, end_time) WITH &&),
    -- a room cannot host two papers at once
    EXCLUDE USING gist (room_id WITH =, exam_date WITH =, timerange(start_time, end_time) WITH &&)
);

-- Invigilator conflicts across papers are checked in the app (needs a join).
CREATE TABLE exam_invigilators (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_schedule_id  bigint NOT NULL REFERENCES exam_schedules(id) ON DELETE CASCADE,
    staff_id          bigint NOT NULL REFERENCES staff(id),
    role              text NOT NULL DEFAULT 'invigilator' CHECK (role IN ('chief','invigilator')),
    UNIQUE (exam_schedule_id, staff_id)
);

CREATE TABLE exam_candidates (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_schedule_id  bigint NOT NULL REFERENCES exam_schedules(id) ON DELETE CASCADE,
    student_id        bigint NOT NULL REFERENCES students(id),
    seat_number       text,
    attendance        text NOT NULL DEFAULT 'expected'
                      CHECK (attendance IN ('expected','present','absent','excused')),
    remarks           text,
    UNIQUE (exam_schedule_id, student_id)
);

-- ---------------------------------------------------------------------
-- 5. COMPUTED RESULTS (snapshots written at validation time)
-- ---------------------------------------------------------------------
-- Reference formula for a subject average in a term (done in Laravel):
--   sum( score / max_score * scale_max * weight ) / sum( weight )
--   over grades with status = 'graded' (absent/excused ignored unless
--   policy says absent = 0), then rounded per grading_policies.
CREATE TABLE subject_term_results (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    bigint NOT NULL REFERENCES students(id),
    class_id      bigint NOT NULL REFERENCES classes(id),
    subject_id    bigint NOT NULL REFERENCES subjects(id),
    term_id       bigint NOT NULL REFERENCES terms(id),
    average       numeric(6,2),                         -- null if nothing graded
    coefficient   numeric(4,2) NOT NULL,                -- snapshot from level_subjects
    class_average numeric(6,2),
    class_min     numeric(6,2),
    class_max     numeric(6,2),
    rank          integer,                              -- only if policy.ranking_enabled
    appreciation  text,                                 -- band label snapshot
    computed_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (student_id, subject_id, term_id)
);
CREATE INDEX idx_str_class ON subject_term_results (class_id, term_id, subject_id);

CREATE TABLE term_results (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        bigint NOT NULL REFERENCES students(id),
    class_id          bigint NOT NULL REFERENCES classes(id),
    term_id           bigint NOT NULL REFERENCES terms(id),
    average           numeric(6,2),                     -- coefficient-weighted overall
    class_average     numeric(6,2),
    rank              integer,
    class_size        integer,
    days_absent       integer NOT NULL DEFAULT 0,       -- snapshot from attendance
    days_late         integer NOT NULL DEFAULT 0,
    days_excused      integer NOT NULL DEFAULT 0,
    appreciation      text,
    needs_support     boolean NOT NULL DEFAULT false,   -- below pass mark or policy threshold
    computed_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (student_id, term_id)
);
CREATE INDEX idx_tr_class ON term_results (class_id, term_id);

CREATE TABLE annual_results (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          bigint NOT NULL REFERENCES students(id),
    class_id            bigint NOT NULL REFERENCES classes(id),
    academic_year_id    bigint NOT NULL REFERENCES academic_years(id),
    average             numeric(6,2),
    rank                integer,
    decision            text NOT NULL DEFAULT 'pending'
                        CHECK (decision IN ('pending','promoted','repeat','conditional','graduated','left')),
    decision_note       text,
    decided_by          bigint REFERENCES users(id),     -- academic director / council
    decided_at          timestamptz,
    UNIQUE (student_id, academic_year_id)
);

