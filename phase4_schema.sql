-- ---------------------------------------------------------------------
-- 10. OFFLINE SYNC
-- Mobile apps queue operations while offline and upload them later.
-- Each operation is logged once (client_uuid) and applied by the server
-- through the same business rules as online requests.
-- ---------------------------------------------------------------------
-- Version counters on entities that can be edited offline
ALTER TABLE attendance_records     ADD COLUMN row_version integer NOT NULL DEFAULT 1;
ALTER TABLE grades                 ADD COLUMN row_version integer NOT NULL DEFAULT 1;
ALTER TABLE assignment_submissions ADD COLUMN row_version integer NOT NULL DEFAULT 1;

CREATE TRIGGER trg_attendance_records_version BEFORE UPDATE ON attendance_records
    FOR EACH ROW EXECUTE FUNCTION fn_bump_row_version();
CREATE TRIGGER trg_grades_version BEFORE UPDATE ON grades
    FOR EACH ROW EXECUTE FUNCTION fn_bump_row_version();
CREATE TRIGGER trg_assignment_submissions_version BEFORE UPDATE ON assignment_submissions
    FOR EACH ROW EXECUTE FUNCTION fn_bump_row_version();

-- How conflicting offline edits are resolved, per entity (school-editable)
CREATE TABLE sync_conflict_policies (
    entity_type  text PRIMARY KEY,                           -- 'attendance_record','grade',...
    strategy     text NOT NULL CHECK (strategy IN ('server_wins','client_wins','last_write_wins','manual_review')),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

INSERT INTO sync_conflict_policies (entity_type, strategy) VALUES
    ('attendance_record',     'last_write_wins'),   -- every change is kept in attendance history anyway
    ('grade',                 'manual_review'),     -- grade conflicts go to a person
    ('assignment_submission', 'server_wins'),
    ('assignment',            'server_wins');

CREATE TABLE sync_operations (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_uuid        uuid NOT NULL UNIQUE,                 -- idempotency key generated on the device
    device_id          bigint REFERENCES devices(id) ON DELETE SET NULL,
    user_id            bigint NOT NULL REFERENCES users(id),
    entity_type        text NOT NULL,
    entity_id          bigint,
    operation          text NOT NULL CHECK (operation IN ('create','update','delete')),
    payload            jsonb NOT NULL,
    base_version       integer,                              -- row_version the client edited from
    client_created_at  timestamptz NOT NULL,
    received_at        timestamptz NOT NULL DEFAULT now(),
    applied_at         timestamptz,
    status             text NOT NULL DEFAULT 'received'
                       CHECK (status IN ('received','applied','duplicate','conflict','rejected')),
    error              text
);
CREATE INDEX idx_sync_ops_user ON sync_operations (user_id, received_at DESC);
CREATE INDEX idx_sync_ops_status ON sync_operations (status) WHERE status IN ('received','conflict');

CREATE TABLE sync_conflicts (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id     bigint NOT NULL UNIQUE REFERENCES sync_operations(id),
    server_snapshot  jsonb NOT NULL,
    client_snapshot  jsonb NOT NULL,
    strategy_used    text NOT NULL,
    status           text NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved')),
    resolution       text CHECK (resolution IN ('keep_server','apply_client','merged')),
    resolved_by      bigint REFERENCES users(id),
    resolved_at      timestamptz,
    note             text,
    CHECK (status = 'open' OR resolution IS NOT NULL)
);

-- Where each device last pulled changes (incremental download)
CREATE TABLE device_sync_state (
    device_id     bigint NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    entity_type   text NOT NULL,
    last_pull_at  timestamptz NOT NULL,
    PRIMARY KEY (device_id, entity_type)
);

