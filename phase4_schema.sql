-- Messages are never edited or deleted. Moderators change status only.
CREATE OR REPLACE FUNCTION fn_messages_guard() RETURNS trigger AS $$
DECLARE
    conv_status text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Messages cannot be deleted. A moderator can hide or remove them.'
            USING ERRCODE = 'check_violation';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT status INTO conv_status FROM conversations WHERE id = NEW.conversation_id;
        IF conv_status IS DISTINCT FROM 'open' THEN
            RAISE EXCEPTION 'Conversation % is not open.', NEW.conversation_id USING ERRCODE = 'check_violation';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM conversation_participants
            WHERE conversation_id = NEW.conversation_id AND user_id = NEW.sender_id
              AND left_at IS NULL AND role <> 'observer'
        ) THEN
            RAISE EXCEPTION 'User % cannot post in conversation %.', NEW.sender_id, NEW.conversation_id
                USING ERRCODE = 'check_violation';
        END IF;
        RETURN NEW;
    END IF;

    -- UPDATE: only status may change
    IF NEW.body IS DISTINCT FROM OLD.body
       OR NEW.sender_id IS DISTINCT FROM OLD.sender_id
       OR NEW.conversation_id IS DISTINCT FROM OLD.conversation_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Message content is immutable.' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_messages_guard
    BEFORE INSERT OR UPDATE OR DELETE ON messages
    FOR EACH ROW EXECUTE FUNCTION fn_messages_guard();

CREATE OR REPLACE FUNCTION fn_message_touch() RETURNS trigger AS $$
