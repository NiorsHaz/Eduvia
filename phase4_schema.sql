-- Teacher <-> guardian pairs that share a child: teachers of the child's class
-- and the class supervisor, with a verified, non-revoked guardian link.
CREATE OR REPLACE VIEW v_teacher_guardian_pairs AS
SELECT DISTINCT t.teacher_user_id, g.user_id AS guardian_user_id, t.student_id
FROM (
    SELECT st.user_id AS teacher_user_id, e.student_id
    FROM class_subject_teachers cst
    JOIN staff st ON st.id = cst.staff_id AND st.user_id IS NOT NULL
    JOIN enrollments e ON e.class_id = cst.class_id AND e.end_date IS NULL AND e.status = 'active'
    WHERE cst.ends_on IS NULL OR cst.ends_on >= current_date
    UNION
    SELECT st.user_id, e.student_id
    FROM classes c
    JOIN staff st ON st.id = c.supervisor_staff_id AND st.user_id IS NOT NULL
    JOIN enrollments e ON e.class_id = c.id AND e.end_date IS NULL AND e.status = 'active'
) t
JOIN student_guardians sg ON sg.student_id = t.student_id
                         AND sg.verified_at IS NOT NULL AND sg.revoked_at IS NULL
JOIN guardians g ON g.id = sg.guardian_id AND g.user_id IS NOT NULL;

