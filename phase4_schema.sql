-- Generic append-only guard, reused by phase 5 tables as well
CREATE OR REPLACE FUNCTION fn_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: % is not allowed. Insert a new row instead.', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'check_violation';
END;
$$ LANGUAGE plpgsql;

-- Bumps row_version on every update (used for offline conflict detection)
CREATE OR REPLACE FUNCTION fn_bump_row_version() RETURNS trigger AS $$
BEGIN
    NEW.row_version := OLD.row_version + 1;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

