    reach       text NOT NULL DEFAULT 'all' CHECK (reach IN ('students','guardians','staff','all')),
    CHECK (
        (audience_type = 'school') OR
        (audience_type = 'level' AND level_id IS NOT NULL) OR
        (audience_type = 'class' AND class_id IS NOT NULL) OR
        (audience_type = 'role'  AND role_name IS NOT NULL)
    )
);

CREATE TABLE event_registrations (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      bigint NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    user_id       bigint NOT NULL REFERENCES users(id),     -- who answered
    student_id    bigint REFERENCES students(id),           -- on behalf of which child, if any
    status        text NOT NULL DEFAULT 'going'
                  CHECK (status IN ('going','not_going','maybe','waitlisted','attended','no_show')),
    note          text,
    responded_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (event_id, user_id, student_id)
);

