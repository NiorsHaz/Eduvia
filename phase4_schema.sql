-- Per-user opt-outs. Critical types cannot be disabled (trigger below).
CREATE TABLE user_notification_preferences (
    user_id               bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    notification_type_id  bigint NOT NULL REFERENCES notification_types(id),
    channel               text NOT NULL CHECK (channel IN ('in_app','push','email','sms')),
    enabled               boolean NOT NULL,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, notification_type_id, channel)
);

CREATE OR REPLACE FUNCTION fn_pref_critical_guard() RETURNS trigger AS $$
DECLARE crit boolean;
BEGIN
    SELECT is_critical INTO crit FROM notification_types WHERE id = NEW.notification_type_id;
    IF crit AND NOT NEW.enabled THEN
        RAISE EXCEPTION 'Critical school notices cannot be disabled.' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pref_critical_guard
    BEFORE INSERT OR UPDATE ON user_notification_preferences
    FOR EACH ROW EXECUTE FUNCTION fn_pref_critical_guard();

