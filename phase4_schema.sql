-- =====================================================================
-- High School Management System: Phase 4 schema (PostgreSQL 15+)
-- Scope: mobile devices, guardian onboarding, notifications and
--        preferences, announcements, moderated messaging, appointments,
--        events and calendar, learning resources, offline sync.
-- Depends on: phase1, phase2, phase2b (setting_definitions), phase3.
--
-- Principles
--   * Communication is controlled, targeted and traceable. Messaging is
--     moderated and append-only; open chat is NOT part of this phase.
--   * Critical notices (emergencies, etc.) cannot be switched off by users.
--   * Offline mobile work is applied through an idempotent sync log:
--     every operation carries a client_uuid, so retries never duplicate.
--   * Who may talk to whom is DATA (messaging_rules), not code.
--   * Mobile apps get no extra privileges: all access still goes through
--     the same server-side authorization as the web application.
-- =====================================================================

