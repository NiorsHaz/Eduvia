-- =====================================================================
-- Phase 2b: configurable school rules (PostgreSQL 15+)
-- Run AFTER phase1_schema.sql and phase2_schema.sql.
--
-- Goal: no school rule is hard-coded. Each school edits its own rules
-- from an admin screen; the application only reads them.
--
-- Layers
--   1. setting_definitions + settings   generic, typed, scoped settings
--   2. grading_policies (extended)      how grades are computed
--   3. grading_policy_subject_rules     per-subject exceptions
--   4. promotion rule sets              promotion/repeat rules as DATA
--   5. versioning + locking             rules can't change under validated results
--   6. snapshots                        results remember which rules produced them
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. GENERIC SETTINGS REGISTRY
-- The admin UI is generated from setting_definitions (label, type,
-- allowed values), so adding a new option needs no new screen.
-- ---------------------------------------------------------------------
CREATE TABLE setting_definitions (
    key            text PRIMARY KEY,                 -- 'attendance.late_minutes_as_absent'
    module         text NOT NULL,                    -- attendance, students, grading, ...
    label_key      text NOT NULL,                    -- i18n key (fr / mg / en)
    description_key text,
    value_type     text NOT NULL CHECK (value_type IN ('boolean','integer','decimal','string','enum','json')),
    allowed_values jsonb,                            -- for enum: ["ignore","zero"]
    default_value  jsonb NOT NULL,
    allowed_scopes text[] NOT NULL DEFAULT ARRAY['school']
                   CHECK (allowed_scopes <@ ARRAY['school','campus','academic_year','level']),
    requires_permission text NOT NULL DEFAULT 'settings.manage'
);

CREATE TABLE settings (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key               text NOT NULL REFERENCES setting_definitions(key) ON DELETE CASCADE,
    campus_id         bigint REFERENCES campuses(id),
    academic_year_id  bigint REFERENCES academic_years(id),
    level_id          bigint REFERENCES levels(id),
    value             jsonb NOT NULL,
    updated_by        bigint REFERENCES users(id),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    -- the app resolves the most specific match: level > year > campus > school > default
    UNIQUE NULLS NOT DISTINCT (key, campus_id, academic_year_id, level_id)
);

