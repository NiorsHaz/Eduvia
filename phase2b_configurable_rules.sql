-- ---------------------------------------------------------------------
-- 2. GRADING POLICIES: extra configurable behaviours
-- ---------------------------------------------------------------------
ALTER TABLE grading_policies
    ADD COLUMN name                    text NOT NULL DEFAULT 'Default',
    -- how an absent student is counted in an assessment
    ADD COLUMN absence_handling        text NOT NULL DEFAULT 'ignore'
        CHECK (absence_handling IN ('ignore','zero','zero_if_unexcused')),
    -- how a missing grade (no row / not_graded) is counted at calculation time
    ADD COLUMN missing_grade_handling  text NOT NULL DEFAULT 'ignore'
        CHECK (missing_grade_handling IN ('ignore','zero','block_validation')),
    -- how assessments inside a subject/term are combined
    ADD COLUMN averaging_method        text NOT NULL DEFAULT 'weighted'
        CHECK (averaging_method IN ('weighted','simple_mean','best_n','drop_lowest')),
    ADD COLUMN averaging_params        jsonb NOT NULL DEFAULT '{}'::jsonb,     -- {"n":3} for best_n
    -- how subject averages combine into the term average
    ADD COLUMN subject_aggregation     text NOT NULL DEFAULT 'coefficient_weighted'
        CHECK (subject_aggregation IN ('coefficient_weighted','simple_mean')),
    -- how term averages combine into the annual average
    ADD COLUMN term_aggregation        text NOT NULL DEFAULT 'weighted_terms'
        CHECK (term_aggregation IN ('weighted_terms','simple_mean','last_term_only')),
    -- a subject average below this value can block promotion (note eliminatoire); NULL = none
    ADD COLUMN eliminatory_mark        numeric(6,2),
    -- minimum graded assessments per subject/term before an average is produced
    ADD COLUMN min_graded_assessments  smallint NOT NULL DEFAULT 1 CHECK (min_graded_assessments >= 0),
    -- ranking
    ADD COLUMN ranking_scope           text NOT NULL DEFAULT 'class' CHECK (ranking_scope IN ('class','level')),
    ADD COLUMN ranking_ties            text NOT NULL DEFAULT 'shared'  CHECK (ranking_ties IN ('shared','break_by_coefficient_subjects')),
    ADD COLUMN show_rank_on_report_card boolean NOT NULL DEFAULT false,
    -- support flag: term average under this value marks "needs support"; NULL = use pass_mark
    ADD COLUMN support_threshold       numeric(6,2),
    -- versioning / locking (section 5)
    ADD COLUMN version                 integer NOT NULL DEFAULT 1,
    ADD COLUMN is_active               boolean NOT NULL DEFAULT true,
    ADD COLUMN locked_at               timestamptz,
    ADD COLUMN locked_reason           text;

-- Replace the old uniqueness so a locked policy can be superseded by a new version
ALTER TABLE grading_policies DROP CONSTRAINT grading_policies_academic_year_id_level_id_key;
CREATE UNIQUE INDEX uq_active_policy ON grading_policies (academic_year_id, level_id)
    NULLS NOT DISTINCT WHERE is_active;

-- ---------------------------------------------------------------------
-- 3. PER-SUBJECT EXCEPTIONS
-- e.g. Sport out of 10, Music not counted in the average, Math core.
-- NULL columns mean "use the policy value".
-- ---------------------------------------------------------------------
CREATE TABLE grading_policy_subject_rules (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id          bigint NOT NULL REFERENCES grading_policies(id) ON DELETE CASCADE,
    subject_id         bigint NOT NULL REFERENCES subjects(id),
    scale_id           bigint REFERENCES grading_scales(id),
    pass_mark          numeric(6,2),
    eliminatory_mark   numeric(6,2),
    counts_in_average  boolean NOT NULL DEFAULT true,      -- false = shown on report card only
    bonus_above        numeric(6,2),                       -- only points above this count (optional subjects)
    is_core            boolean NOT NULL DEFAULT false,     -- used by promotion metrics
    UNIQUE (policy_id, subject_id)
);

-- ---------------------------------------------------------------------
-- 4. PROMOTION RULES AS DATA
-- A rule set is an ordered list of rules; the FIRST rule whose condition
-- matches decides the outcome. Conditions are structured JSON evaluated
-- by a whitelisted evaluator in Laravel (never eval / raw SQL from JSON).
-- ---------------------------------------------------------------------
-- Whitelist of values a rule may reference
CREATE TABLE rule_metrics (
    code         text PRIMARY KEY,
    label_key    text NOT NULL,
    value_type   text NOT NULL CHECK (value_type IN ('number','boolean','string')),
    params_schema jsonb NOT NULL DEFAULT '{}'::jsonb
);

