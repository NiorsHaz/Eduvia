 ('subjects_below_eliminatory',  'rules.metric.subjects_below_elim',   'number',  '{"core_only":"boolean"}'),
 ('core_subjects_average',       'rules.metric.core_average',          'number',  '{}'),
 ('unexcused_absence_days',      'rules.metric.unexcused_absences',    'number',  '{}'),
 ('previous_year_decision',      'rules.metric.previous_decision',     'string',  '{}'),
 ('is_final_level',              'rules.metric.is_final_level',        'boolean', '{}');

CREATE TABLE promotion_rule_sets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id   bigint NOT NULL REFERENCES grading_policies(id) ON DELETE CASCADE,
    name        text NOT NULL,
    description text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (policy_id, name)
);

CREATE TABLE promotion_rules (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_set_id   bigint NOT NULL REFERENCES promotion_rule_sets(id) ON DELETE CASCADE,
    priority      smallint NOT NULL,                 -- lowest number is evaluated first
    label         text NOT NULL,                     -- shown to staff: "Average >= 10, no eliminatory"
    -- Condition tree. Example:
    -- {"all":[
    --    {"metric":"annual_average","op":">=","value":10},
    --    {"metric":"subjects_below_eliminatory","op":"=","value":0}
    -- ]}
    -- Groups: "all" (AND), "any" (OR), "not". Ops: = != > >= < <= in
    condition     jsonb NOT NULL,
    outcome       text NOT NULL CHECK (outcome IN ('promoted','repeat','conditional','graduated','left','council_review')),
    requires_human_confirmation boolean NOT NULL DEFAULT true,   -- suggestion vs automatic decision
    is_active     boolean NOT NULL DEFAULT true,
    UNIQUE (rule_set_id, priority)
);

-- Which rule set applies to which level (NULL level = default)
CREATE TABLE promotion_rule_set_levels (
    rule_set_id  bigint NOT NULL REFERENCES promotion_rule_sets(id) ON DELETE CASCADE,
    level_id     bigint REFERENCES levels(id),
    UNIQUE NULLS NOT DISTINCT (rule_set_id, level_id)
);

ALTER TABLE annual_results DROP CONSTRAINT annual_results_decision_check;
ALTER TABLE annual_results ADD CONSTRAINT annual_results_decision_check
    CHECK (decision IN ('pending','promoted','repeat','conditional','graduated','left','council_review'));

-- ---------------------------------------------------------------------
-- 5. LOCKING: rules cannot change once results depend on them
-- The app sets locked_at when the first term is validated under the policy.
-- To change rules afterwards: clone to a new version (function below).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_policy_lock_guard() RETURNS trigger AS $$
BEGIN
    IF OLD.locked_at IS NOT NULL AND (
        (to_jsonb(NEW) - 'is_active' - 'updated_at' - 'locked_reason')
        IS DISTINCT FROM
        (to_jsonb(OLD) - 'is_active' - 'updated_at' - 'locked_reason')
    ) THEN
        RAISE EXCEPTION 'Grading policy % is locked (results already validated). Create a new version instead.', OLD.id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_policy_lock_guard
    BEFORE UPDATE ON grading_policies
    FOR EACH ROW EXECUTE FUNCTION fn_policy_lock_guard();

-- Subject rules and promotion rules of a locked policy are frozen too
CREATE OR REPLACE FUNCTION fn_policy_children_guard() RETURNS trigger AS $$
DECLARE
    pid bigint;
    locked timestamptz;
BEGIN
    IF TG_TABLE_NAME = 'grading_policy_subject_rules' THEN
        pid := COALESCE(NEW.policy_id, OLD.policy_id);
    ELSIF TG_TABLE_NAME = 'promotion_rule_sets' THEN
        pid := COALESCE(NEW.policy_id, OLD.policy_id);
    ELSE  -- promotion_rules
        SELECT policy_id INTO pid FROM promotion_rule_sets WHERE id = COALESCE(NEW.rule_set_id, OLD.rule_set_id);
    END IF;
    SELECT locked_at INTO locked FROM grading_policies WHERE id = pid;
    IF locked IS NOT NULL THEN
        RAISE EXCEPTION 'Grading policy % is locked. Create a new version to change its rules.', pid
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_gpsr_guard BEFORE INSERT OR UPDATE OR DELETE ON grading_policy_subject_rules
    FOR EACH ROW EXECUTE FUNCTION fn_policy_children_guard();
CREATE TRIGGER trg_prs_guard  BEFORE INSERT OR UPDATE OR DELETE ON promotion_rule_sets
    FOR EACH ROW EXECUTE FUNCTION fn_policy_children_guard();
CREATE TRIGGER trg_pr_guard   BEFORE INSERT OR UPDATE OR DELETE ON promotion_rules
    FOR EACH ROW EXECUTE FUNCTION fn_policy_children_guard();

-- Clone a policy (with its subject rules and promotion rules) into a new
-- academic year or as a new version. Used for "copy last year's rules"
-- and for changing a locked policy.
-- Pass the same year id to create a new version; the old one is deactivated.
CREATE OR REPLACE FUNCTION fn_clone_grading_policy(p_source bigint, p_target_year bigint)
RETURNS bigint AS $$
DECLARE
    src        grading_policies%ROWTYPE;
    new_id     bigint;
    new_set    bigint;
    old_set    record;
BEGIN
    SELECT * INTO src FROM grading_policies WHERE id = p_source;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Policy % not found', p_source;
    END IF;

    IF p_target_year = src.academic_year_id THEN
        UPDATE grading_policies SET is_active = false, updated_at = now() WHERE id = p_source;
    END IF;

    INSERT INTO grading_policies (
        academic_year_id, level_id, scale_id, pass_mark, rounding_decimals, rounding_mode,
        ranking_enabled, term_weights, promotion_rules, name, absence_handling,
        missing_grade_handling, averaging_method, averaging_params, subject_aggregation,
        term_aggregation, eliminatory_mark, min_graded_assessments, ranking_scope, ranking_ties,
        show_rank_on_report_card, support_threshold, version, is_active)
    VALUES (
        p_target_year, src.level_id, src.scale_id, src.pass_mark, src.rounding_decimals, src.rounding_mode,
        src.ranking_enabled, '{}'::jsonb, src.promotion_rules, src.name, src.absence_handling,
        src.missing_grade_handling, src.averaging_method, src.averaging_params, src.subject_aggregation,
        src.term_aggregation, src.eliminatory_mark, src.min_graded_assessments, src.ranking_scope, src.ranking_ties,
        src.show_rank_on_report_card, src.support_threshold,
        CASE WHEN p_target_year = src.academic_year_id THEN src.version + 1 ELSE 1 END,
        true)
    RETURNING id INTO new_id;
    -- term_weights depend on the target year's terms: the admin re-enters them

    INSERT INTO grading_policy_subject_rules (policy_id, subject_id, scale_id, pass_mark,
            eliminatory_mark, counts_in_average, bonus_above, is_core)
    SELECT new_id, subject_id, scale_id, pass_mark, eliminatory_mark, counts_in_average, bonus_above, is_core
    FROM grading_policy_subject_rules WHERE policy_id = p_source;

    FOR old_set IN SELECT * FROM promotion_rule_sets WHERE policy_id = p_source LOOP
        INSERT INTO promotion_rule_sets (policy_id, name, description)
        VALUES (new_id, old_set.name, old_set.description)
        RETURNING id INTO new_set;

        INSERT INTO promotion_rules (rule_set_id, priority, label, condition, outcome,
                requires_human_confirmation, is_active)
        SELECT new_set, priority, label, condition, outcome, requires_human_confirmation, is_active
        FROM promotion_rules WHERE rule_set_id = old_set.id;

        INSERT INTO promotion_rule_set_levels (rule_set_id, level_id)
        SELECT new_set, level_id FROM promotion_rule_set_levels WHERE rule_set_id = old_set.id;
    END LOOP;

    RETURN new_id;
END;
$$ LANGUAGE plpgsql;

