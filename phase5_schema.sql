-- Once a period is approved, its payslips are frozen (payment fields stay editable)
CREATE OR REPLACE FUNCTION fn_payslip_guard() RETURNS trigger AS $$
DECLARE
    pid bigint;
    st  text;
BEGIN
    pid := COALESCE(NEW.period_id, OLD.period_id);
    SELECT status INTO st FROM payroll_periods WHERE id = pid;
    IF st IN ('approved','paid','closed') THEN
        IF TG_OP IN ('INSERT','DELETE') THEN
            RAISE EXCEPTION 'Payroll period % is %: payslips cannot be added or removed.', pid, st
                USING ERRCODE = 'check_violation';
        END IF;
        IF NEW.gross_amount     IS DISTINCT FROM OLD.gross_amount
        OR NEW.total_deductions IS DISTINCT FROM OLD.total_deductions
        OR NEW.net_amount       IS DISTINCT FROM OLD.net_amount
        OR NEW.staff_id         IS DISTINCT FROM OLD.staff_id
        OR NEW.period_id        IS DISTINCT FROM OLD.period_id THEN
            RAISE EXCEPTION 'Payroll period % is %: payslip amounts are frozen.', pid, st
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_payslip_guard
    BEFORE INSERT OR UPDATE OR DELETE ON payslips
    FOR EACH ROW EXECUTE FUNCTION fn_payslip_guard();

CREATE OR REPLACE FUNCTION fn_payslip_line_guard() RETURNS trigger AS $$
DECLARE
    st text;
BEGIN
    SELECT pp.status INTO st
    FROM payslips p JOIN payroll_periods pp ON pp.id = p.period_id
    WHERE p.id = COALESCE(NEW.payslip_id, OLD.payslip_id);
    IF st IN ('approved','paid','closed') THEN
        RAISE EXCEPTION 'Payslip lines of a % payroll period are frozen.', st
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_payslip_line_guard
    BEFORE INSERT OR UPDATE OR DELETE ON payslip_lines
    FOR EACH ROW EXECUTE FUNCTION fn_payslip_line_guard();

