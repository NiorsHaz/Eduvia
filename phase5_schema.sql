-- Remaining leave per person, type and year (leave year taken as calendar year of the start date;
-- schools with another leave year use the hr.leave_year_start setting in the app layer)
CREATE OR REPLACE VIEW v_leave_balances AS
SELECT le.staff_id, le.leave_type_id, le.year,
       (le.entitled_days + le.carried_over_days + le.adjustment_days) AS total_days,
       COALESCE(u.used, 0) AS used_days,
       (le.entitled_days + le.carried_over_days + le.adjustment_days - COALESCE(u.used, 0)) AS remaining_days
FROM leave_entitlements le
LEFT JOIN LATERAL (
    SELECT sum(lr.days) AS used
    FROM leave_requests lr
    WHERE lr.staff_id = le.staff_id AND lr.leave_type_id = le.leave_type_id
      AND lr.status = 'approved' AND extract(year FROM lr.start_date) = le.year
) u ON true;

-- Lessons of teachers on approved leave that still have no substitute or cancellation
CREATE OR REPLACE VIEW v_lessons_needing_cover AS
SELECT lr.id AS leave_request_id, lr.staff_id, d::date AS lesson_date,
       te.id AS timetable_entry_id, te.class_id, te.subject_id, te.start_time, te.end_time
FROM leave_requests lr
CROSS JOIN LATERAL generate_series(lr.start_date, lr.end_date, interval '1 day') AS d
JOIN timetable_entries te
  ON te.staff_id = lr.staff_id
 AND te.day_of_week = extract(isodow FROM d)::int
 AND daterange(te.valid_from, te.valid_to, '[]') @> d::date
LEFT JOIN timetable_exceptions tx
  ON tx.timetable_entry_id = te.id AND tx.exception_date = d::date
WHERE lr.status = 'approved' AND tx.id IS NULL;

CREATE OR REPLACE VIEW v_teacher_workload AS
SELECT te.academic_year_id, te.staff_id,
       round(sum(extract(epoch FROM (te.end_time - te.start_time)) / 3600.0)::numeric, 1) AS weekly_hours,
       count(DISTINCT te.class_id) AS classes_taught
FROM timetable_entries te
WHERE te.valid_to IS NULL OR te.valid_to >= current_date
GROUP BY te.academic_year_id, te.staff_id;

