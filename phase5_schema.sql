-- =====================================================================
-- High School Management System: Phase 5 schema (PostgreSQL 15+)
-- Scope: library, inventory and equipment, school transport, discipline,
--        document requests and issuance, staff HR (leave, attendance,
--        workload), optional payroll, analytics, integrations, privacy.
-- Depends on: phase1 to phase4 (uses fn_append_only from phase 4,
--             number_series from phase 3, setting_definitions from 2b).
--
-- Principles
--   * Every module is OPTIONAL: each has a modules.* setting so a school
--     enables only what it uses. The tables exist; the app hides the UI.
--   * Sensitive modules (discipline, payroll) have restricted access,
--     append-only history, and access logs.
--   * Integrations store a REFERENCE to a secret, never the secret.
--   * GPS tracking, biometrics and AI are NOT built here. GPS has an
--     optional table behind a setting; biometrics and AI need their own
--     privacy and legal review and are deliberately absent.
--   * Money is bigint in whole currency units, as in phase 3.
-- =====================================================================

