CREATE TABLE data_retention_policies (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity           text NOT NULL UNIQUE
                     CHECK (entity IN ('discipline_incidents','messages','notifications','login_history',
                                       'vehicle_positions','report_exports','sync_operations',
                                       'student_records_after_exit','applications_not_enrolled')),
    retention_months integer NOT NULL CHECK (retention_months > 0),
    action           text NOT NULL CHECK (action IN ('archive','anonymize','delete')),
    is_active        boolean NOT NULL DEFAULT false,         -- the school activates each rule after legal review
    updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE privacy_requests (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type     text NOT NULL CHECK (subject_type IN ('student','guardian','staff')),
    subject_id       bigint NOT NULL,
    requested_by     bigint REFERENCES users(id),
    request_type     text NOT NULL CHECK (request_type IN ('access','correction','export','deletion','restriction')),
    details          text,
    status           text NOT NULL DEFAULT 'received'
                     CHECK (status IN ('received','verifying_identity','in_progress','completed','rejected')),
    due_date         date,
    handled_by       bigint REFERENCES users(id),
    response_note    text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    completed_at     timestamptz,
    CHECK (status <> 'rejected' OR response_note IS NOT NULL)
);
CREATE INDEX idx_privacy_status ON privacy_requests (status, due_date);

