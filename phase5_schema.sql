-- Keep the copy status in step with its loans
CREATE OR REPLACE FUNCTION fn_loan_copy_status() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE book_copies SET status = 'on_loan'
        WHERE id = NEW.copy_id AND status IN ('available','reserved');
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Copy % is not available for loan.', NEW.copy_id USING ERRCODE = 'check_violation';
        END IF;
    ELSIF TG_OP = 'UPDATE' AND OLD.status = 'active' AND NEW.status <> 'active' THEN
        UPDATE book_copies
        SET status = CASE
                WHEN NEW.status = 'lost' THEN 'lost'
                WHEN NEW.condition_on_return = 'damaged' THEN 'damaged'
                ELSE 'available' END,
            condition = COALESCE(NEW.condition_on_return, condition)
        WHERE id = NEW.copy_id;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_loan_copy_status
    AFTER INSERT OR UPDATE ON library_loans
    FOR EACH ROW EXECUTE FUNCTION fn_loan_copy_status();

