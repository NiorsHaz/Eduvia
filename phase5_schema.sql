CREATE OR REPLACE VIEW v_route_occupancy AS
SELECT r.id AS route_id, r.name, r.direction, v.capacity,
       count(st.id) FILTER (WHERE st.status = 'active' AND (st.end_date IS NULL OR st.end_date > current_date)) AS assigned
FROM transport_routes r
LEFT JOIN vehicles v ON v.id = r.vehicle_id
LEFT JOIN student_transport st ON st.route_id = r.id
GROUP BY r.id, r.name, r.direction, v.capacity;

