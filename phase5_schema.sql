-- Stock can never go negative (row lock serializes concurrent issues)
CREATE OR REPLACE FUNCTION fn_stock_non_negative() RETURNS trigger AS $$
DECLARE
    level numeric;
BEGIN
    PERFORM 1 FROM stock_items WHERE id = NEW.stock_item_id FOR UPDATE;
    SELECT COALESCE(sum(quantity),0) INTO level FROM stock_movements WHERE stock_item_id = NEW.stock_item_id;
    IF level < 0 THEN
        RAISE EXCEPTION 'Stock item % would go negative (%).', NEW.stock_item_id, level
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stock_non_negative
    AFTER INSERT ON stock_movements
    FOR EACH ROW EXECUTE FUNCTION fn_stock_non_negative();

CREATE OR REPLACE VIEW v_stock_levels AS
SELECT i.id AS stock_item_id, i.sku, i.name, i.unit, i.reorder_threshold,
       COALESCE(sum(m.quantity),0) AS quantity_on_hand
FROM stock_items i
LEFT JOIN stock_movements m ON m.stock_item_id = i.id
WHERE i.is_active
GROUP BY i.id;

CREATE OR REPLACE VIEW v_low_stock AS
SELECT * FROM v_stock_levels WHERE quantity_on_hand <= reorder_threshold;

