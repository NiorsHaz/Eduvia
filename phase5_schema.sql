-- Heavy aggregates are materialized; a scheduled job refreshes them
-- (REFRESH MATERIALIZED VIEW CONCURRENTLY, which needs the unique indexes below)
CREATE MATERIALIZED VIEW mv_attendance_daily AS
SELECT s.class_id, s.session_date,
       count(*) FILTER (WHERE r.status = 'present')    AS present,
       count(*) FILTER (WHERE r.status = 'absent')     AS absent,
       count(*) FILTER (WHERE r.status = 'late')       AS late,
       count(*) FILTER (WHERE r.status = 'excused')    AS excused,
       count(*) FILTER (WHERE r.status = 'left_early') AS left_early,
       count(*)                                        AS total
FROM attendance_sessions s
JOIN attendance_records r ON r.session_id = s.id
WHERE s.timetable_entry_id IS NULL                         -- daily roll call only
GROUP BY s.class_id, s.session_date;
CREATE UNIQUE INDEX uq_mv_attendance_daily ON mv_attendance_daily (class_id, session_date);

CREATE MATERIALIZED VIEW mv_enrollment_by_class AS
SELECT c.academic_year_id, c.level_id, c.id AS class_id, count(e.id) AS students
FROM classes c
LEFT JOIN enrollments e ON e.class_id = c.id AND e.end_date IS NULL AND e.status = 'active'
GROUP BY c.academic_year_id, c.level_id, c.id;
CREATE UNIQUE INDEX uq_mv_enrollment ON mv_enrollment_by_class (class_id);

-- Absence and lateness counts over the last 30 days (thresholds are settings in the app)
CREATE OR REPLACE VIEW v_absence_30d AS
SELECT r.student_id,
       count(*) FILTER (WHERE r.status = 'absent') AS absences_30d,
       count(*) FILTER (WHERE r.status = 'late')   AS lates_30d
FROM attendance_records r
JOIN attendance_sessions s ON s.id = r.session_id
WHERE s.session_date >= current_date - 30 AND s.timetable_entry_id IS NULL
GROUP BY r.student_id;

-- Indicators that combine academic results and attendance for support teams.
-- It informs a human follow-up; it never decides anything about a student.
CREATE OR REPLACE VIEW v_support_indicators AS
SELECT DISTINCT ON (tr.student_id)
       tr.student_id, tr.class_id, tr.term_id, tr.average, tr.needs_support,
       COALESCE(a.absences_30d, 0) AS absences_30d,
       COALESCE(a.lates_30d, 0)    AS lates_30d
FROM term_results tr
JOIN terms t ON t.id = tr.term_id
LEFT JOIN v_absence_30d a ON a.student_id = tr.student_id
ORDER BY tr.student_id, t.end_date DESC;

-- ---------------------------------------------------------------------
-- 9. EXTERNAL INTEGRATIONS (SMS, email, payment gateways, accounting, GPS)
-- Only a REFERENCE to the secret is stored (vault or environment name).
-- ---------------------------------------------------------------------
CREATE TABLE integration_connections (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              text NOT NULL UNIQUE,
    kind              text NOT NULL CHECK (kind IN ('sms','email','payment_gateway','accounting','gps','other')),
    provider          text NOT NULL,
    display_name      text NOT NULL,
    config            jsonb NOT NULL DEFAULT '{}'::jsonb,    -- non-secret settings only
    secret_reference  text,                                  -- name of the secret, never its value
    status            text NOT NULL DEFAULT 'disabled' CHECK (status IN ('disabled','enabled','error')),
    last_success_at   timestamptz,
    last_error        text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

-- Inbound webhooks and outbound calls. The idempotency key makes
-- repeated provider callbacks (common with payment gateways) harmless.
CREATE TABLE integration_events (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id    bigint NOT NULL REFERENCES integration_connections(id),
    direction        text NOT NULL CHECK (direction IN ('inbound','outbound')),
    event_type       text NOT NULL,
    idempotency_key  text,
    payload          jsonb NOT NULL,
    status           text NOT NULL DEFAULT 'received' CHECK (status IN ('received','processed','failed','ignored')),
    attempts         smallint NOT NULL DEFAULT 0,
    error            text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    processed_at     timestamptz,
    UNIQUE (connection_id, idempotency_key)
);
CREATE INDEX idx_integration_events_status ON integration_events (status, created_at) WHERE status IN ('received','failed');

