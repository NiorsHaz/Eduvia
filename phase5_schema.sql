CREATE OR REPLACE FUNCTION fn_student_transport_guard() RETURNS trigger AS $$
DECLARE
    r_direction text;
    cap         integer;
    assigned    integer;
    stop_route  bigint;
BEGIN
    SELECT direction INTO r_direction FROM transport_routes WHERE id = NEW.route_id;
    NEW.direction := r_direction;

    SELECT route_id INTO stop_route FROM route_stops WHERE id = NEW.stop_id;
    IF stop_route IS DISTINCT FROM NEW.route_id THEN
        RAISE EXCEPTION 'Stop % does not belong to route %.', NEW.stop_id, NEW.route_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.status = 'active' THEN
        SELECT v.capacity INTO cap
        FROM transport_routes r JOIN vehicles v ON v.id = r.vehicle_id
        WHERE r.id = NEW.route_id;
        IF cap IS NOT NULL THEN
            SELECT count(*) INTO assigned
            FROM student_transport
            WHERE route_id = NEW.route_id AND status = 'active'
              AND (end_date IS NULL OR end_date > current_date)
              AND id IS DISTINCT FROM NEW.id;
            IF assigned >= cap THEN
                RAISE EXCEPTION 'Route % is at vehicle capacity (%).', NEW.route_id, cap
                    USING ERRCODE = 'check_violation';
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_student_transport_guard
    BEFORE INSERT OR UPDATE ON student_transport
    FOR EACH ROW EXECUTE FUNCTION fn_student_transport_guard();

